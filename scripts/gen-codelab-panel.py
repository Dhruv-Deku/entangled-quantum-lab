"""Generate public/ui/codelab.uikitml: the Code Lab editor and its token keyboard."""
from pathlib import Path

LINES = 10
ROWS = [
    ['h', 'x', 'y', 'z', 's', 'sdg', 't', 'tdg'],
    ['rx', 'ry', 'rz', 'cx', 'cz', 'swap', 'ccx', 'measure'],
    ['q0', 'q1', 'q2', 'q3', 'q4', 'pi', 'pi/2', 'pi/4', '-pi/2'],
    ['Up', 'Down', 'Delete', 'Clear', 'Link'],
    ['- qubit', '+ qubit', 'Example', 'From orbs'],
]


def key_id(label: str) -> str:
    return 'lab-k-' + label.replace('-pi/2', 'mpi2').replace('/', '').replace('+ ', 'add').replace('- ', 'sub').replace(' ', '').lower()


rows = []
for i in range(LINES):
    rows.append(f'    <div id="lab-r-{i}" class="line"><div id="lab-n-{i}" class="no">{i + 1}</div><div id="lab-t-{i}" class="ln">-</div></div>')
keys = []
for r, row in enumerate(ROWS):
    cls = 'gate' if r < 2 else 'arg' if r == 2 else 'edit'
    cells = '\n'.join(f'    <div id="{key_id(k)}" class="key {cls}"><div class="kt">{k}</div></div>' for k in row)
    keys.append(f'  <div class="keys">\n{cells}\n  </div>')

src = '''<!--
  Code Lab: write your own program in OpenQASM 3 with a token keyboard (no
  typing needed in a headset). Generated by scripts/gen-codelab-panel.py; edit
  that instead. UIKit units are cm.
-->
<style>
  .card {
    flex-direction: column;
    width: 460;
    gap: 8;
    padding-top: 18;
    padding-bottom: 16;
    padding-left: 18;
    padding-right: 18;
    background-color: #1b1c1f;
    border-radius: 24;
    border-width: 1;
    border-color: #34363b;
  }
  .head { flex-direction: row; justify-content: space-between; align-items: center; }
  .titles { flex-direction: column; gap: 2; }
  .eyebrow { font-size: 11; font-weight: 600; color: #8a8d93; }
  .title { font-size: 18; font-weight: 700; color: #f2f3f5; }
  .btns { flex-direction: row; gap: 6; align-items: center; }
  .btn {
    height: 30;
    padding-left: 13;
    padding-right: 13;
    border-radius: 15;
    align-items: center;
    justify-content: center;
    background-color: #34363b;
    cursor: pointer;
  }
  .bt { font-size: 12; font-weight: 700; color: #e4e6eb; }
  .code {
    flex-direction: column;
    gap: 2;
    padding-top: 8;
    padding-bottom: 8;
    padding-left: 8;
    padding-right: 8;
    border-radius: 14;
    background-color: #141517;
  }
  .line { flex-direction: row; align-items: center; padding-left: 4; border-radius: 6; }
  .no { width: 18; margin-right: 8; font-size: 10; color: #55585e; text-align: right; }
  .ln { font-size: 12; color: #c9ccd1; }
  .status { font-size: 11; color: #8a8d93; }
  .keys { flex-direction: row; gap: 5; flex-wrap: wrap; }
  .key {
    height: 26;
    padding-left: 9;
    padding-right: 9;
    border-radius: 13;
    align-items: center;
    justify-content: center;
    cursor: pointer;
  }
  .gate { background-color: #2c3a52; }
  .arg { background-color: #2f3135; }
  .edit { background-color: #26272b; }
  .kt { font-size: 11; font-weight: 700; color: #e4e6eb; }
</style>
<div class="card">
  <div class="head">
    <div class="titles">
      <div id="lab-eyebrow" class="eyebrow">Code Lab</div>
      <div class="title">Your program</div>
    </div>
    <div class="btns">
      <div id="lab-step" class="btn"><div class="bt">Step</div></div>
      <div id="lab-run" class="btn"><div class="bt">Run</div></div>
      <div id="lab-close" class="btn"><div class="bt">Close</div></div>
    </div>
  </div>
  <div class="code">
''' + '\n'.join(rows) + '''
  </div>
  <div id="lab-status" class="status">Tap a gate, then its qubits.</div>
''' + '\n'.join(keys) + '''
</div>
'''
Path('public/ui/codelab.uikitml').write_text(src, encoding='utf8')
print('keys:', [key_id(k) for row in ROWS for k in row])
