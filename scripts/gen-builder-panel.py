"""Generate public/ui/builder.uikitml: the circuit builder grid (14 steps x 4 qubits).

Each cell is drawn with plain boxes so it needs no special font glyphs:
left wire | (top link line, glyph, bottom link line) | right wire.
Run: python scripts/gen-builder-panel.py
"""
from pathlib import Path

COLS, ROWS = 14, 4
TOOLS = ['h', 'x', 'y', 'z', 's', 'sdg', 't', 'tdg', 'sx', 'sxdg', 'rx', 'ry', 'rz', 'ctrl', 'anti', 'target', 'swap', 'g1', 'g2', 'g3']

style = """
<style>
  .panel {
    flex-direction: column;
    gap: 8;
    padding-top: 14;
    padding-bottom: 14;
    padding-left: 14;
    padding-right: 14;
    background-color: #242528;
    border-radius: 26;
    border-width: 1;
    border-color: #34363b;
  }
  .head { flex-direction: row; align-items: center; justify-content: space-between; }
  .title { font-size: 15; font-weight: 700; color: #f2f3f5; }
  .btn {
    height: 30;
    padding-left: 14;
    padding-right: 14;
    border-radius: 15;
    align-items: center;
    justify-content: center;
    background-color: #34363b;
    cursor: pointer;
  }
  .bt { font-size: 12; font-weight: 600; color: #e4e6eb; }
  .palette { flex-direction: row; flex-wrap: wrap; gap: 5; }
  .tile {
    width: 36;
    height: 36;
    border-radius: 10;
    align-items: center;
    justify-content: center;
    background-color: #2d2f33;
    cursor: pointer;
  }
  .info { font-size: 11; color: #b8bbc1; }
  .status { font-size: 12; font-weight: 600; color: #8a8d93; }
  .grid { flex-direction: column; padding-top: 4; padding-bottom: 4; border-radius: 14; background-color: #1d1e21; }
  .row { flex-direction: row; align-items: center; }
  .arow { flex-direction: row; align-items: center; gap: 8; }
  .ql { width: 26; font-size: 11; font-weight: 700; color: #8a8d93; padding-left: 6; }
  .cell { width: 40; height: 40; flex-direction: row; align-items: center; cursor: pointer; border-radius: 6; }
  .wire { flex-grow: 1; height: 2; background-color: #4a4c52; }
  .mid { width: 26; height: 40; flex-direction: column; align-items: center; }
  .link { width: 2; flex-grow: 1; background-color: #1d1e21; }
  .g { width: 26; height: 2; align-items: center; justify-content: center; background-color: #4a4c52; }
  .gl { flex-shrink: 0; align-items: center; justify-content: center; font-size: 11; font-weight: 700; color: #e4e6eb; }
</style>
"""

lines = ['<!--', '  Circuit builder: a palette of tools and a grid of steps by qubits in', '  cross-dot notation. Generated by scripts/gen-builder-panel.py; edit that instead.', '-->', style.strip(), '<div class="panel">']
lines.append('  <div class="head">')
lines.append('    <div id="b-title" class="title">Build</div>')
lines.append('    <div class="row">')
lines.append('      <div id="b-clear" class="btn"><div class="bt">Clear</div></div>')
lines.append('    </div>')
lines.append('  </div>')
lines.append('  <div class="palette">')
for t in TOOLS:
    lines.append(f'    <div id="p-{t}" class="tile"><div id="p-{t}-g" class="g"><div id="p-{t}-gl" class="gl">-</div></div></div>')
lines.append('  </div>')
lines.append('  <div id="b-info" class="info">Tap a tool, then tap the grid.</div>')
# angle for new Rx / Ry / Rz cells (shown only while one of them is selected)
lines.append('  <div id="b-angle-row" class="arow">')
lines.append('    <div class="info">Angle for new rotations:</div>')
lines.append('    <div id="b-angle-down" class="btn"><div class="bt">-</div></div>')
lines.append('    <div id="b-angle" class="bt">pi/2</div>')
lines.append('    <div id="b-angle-up" class="btn"><div class="bt">+</div></div>')
lines.append('  </div>')
lines.append('  <div class="grid">')
for r in range(ROWS):
    lines.append(f'    <div id="b-row-{r}" class="row">')
    lines.append(f'      <div id="b-q-{r}" class="ql">q{r}</div>')
    for c in range(COLS):
        k = f'c-{c}-{r}'
        lines.append(
            f'      <div id="{k}" class="cell"><div class="wire"></div><div class="mid">'
            f'<div id="{k}-t" class="link"></div><div id="{k}-g" class="g"><div id="{k}-gl" class="gl">-</div></div>'
            f'<div id="{k}-b" class="link"></div></div><div class="wire"></div></div>'
        )
    lines.append('    </div>')
lines.append('  </div>')
lines.append('  <div id="b-status" class="status">-</div>')
lines.append('</div>')

out = Path(__file__).resolve().parent.parent / 'public' / 'ui' / 'builder.uikitml'
out.write_text('\n'.join(lines) + '\n', encoding='utf8')
print(f'wrote {out} ({COLS}x{ROWS} cells, {len(TOOLS)} tools)')
