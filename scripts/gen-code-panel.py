"""Generate public/ui/code.uikitml: the code window.

Format tabs (Qiskit, OpenQASM 3, PennyLane), Zoom, a page of numbered code lines
(each split into a coloured gate name and the rest, since UIKit text has one
colour per element and ignores line breaks), and Back / More, Simplify, Copy link.
Run: python scripts/gen-code-panel.py
"""
from pathlib import Path

LINES = 10
TABS = [('qiskit', 'Qiskit'), ('qasm', 'OpenQASM 3'), ('pennylane', 'PennyLane')]

style = """
<style>
  .card {
    flex-direction: column;
    width: 420;
    gap: 10;
    padding-top: 18;
    padding-bottom: 18;
    padding-left: 20;
    padding-right: 20;
    background-color: #1b1c1f;
    border-radius: 24;
    border-width: 1;
    border-color: #34363b;
  }
  .head { flex-direction: row; justify-content: space-between; align-items: center; }
  .titles { flex-direction: column; gap: 2; }
  .eyebrow { font-size: 11; font-weight: 600; color: #8a8d93; }
  .title { font-size: 18; font-weight: 700; color: #f2f3f5; }
  .btns { flex-direction: row; gap: 6; align-items: center; }
  .btn {
    height: 32;
    padding-left: 13;
    padding-right: 13;
    border-radius: 16;
    align-items: center;
    justify-content: center;
    background-color: #34363b;
    cursor: pointer;
  }
  .bt { font-size: 12; font-weight: 600; color: #e4e6eb; }
  .tabs {
    flex-direction: row;
    gap: 4;
    padding-top: 4;
    padding-bottom: 4;
    padding-left: 4;
    padding-right: 4;
    border-radius: 20;
    background-color: #242528;
  }
  .tab {
    flex-grow: 1;
    height: 30;
    border-radius: 15;
    align-items: center;
    justify-content: center;
    background-color: #242528;
    cursor: pointer;
  }
  .tl { font-size: 12; font-weight: 700; color: #8a8d93; }
  .note { font-size: 11; color: #8a8d93; }
  .code {
    flex-direction: column;
    gap: 3;
    padding-top: 10;
    padding-bottom: 10;
    padding-left: 10;
    padding-right: 10;
    border-radius: 14;
    background-color: #141517;
  }
  .row { flex-direction: row; align-items: center; }
  .no { width: 18; margin-right: 8; font-size: 10; color: #55585e; text-align: right; }
  .hd { font-size: 12; font-weight: 600; color: #8fb7ff; }
  .ln { font-size: 12; color: #c9ccd1; }
  .foot { flex-direction: row; justify-content: space-between; align-items: center; }
</style>
"""

lines = [
    '<!--',
    '  Code window: the circuit as Qiskit, OpenQASM 3 or PennyLane, a page at a time,',
    '  with Zoom. Generated by scripts/gen-code-panel.py; edit that instead.',
    '  UIKit units are cm.',
    '-->',
    style.strip(),
    '<div class="card">',
    '  <div class="head">',
    '    <div class="titles">',
    '      <div id="code-eyebrow" class="eyebrow">Code</div>',
    '      <div id="code-title" class="title">Your circuit</div>',
    '    </div>',
    '    <div class="btns">',
    '      <div id="code-zoom" class="btn"><div id="code-zoom-label" class="bt">Zoom</div></div>',
    '      <div id="code-close" class="btn"><div class="bt">Close</div></div>',
    '    </div>',
    '  </div>',
    '  <div class="tabs">',
]
for key, label in TABS:
    lines.append(f'    <div id="code-tab-{key}" class="tab"><div id="code-tab-{key}-l" class="tl">{label}</div></div>')
lines += [
    '  </div>',
    '  <div id="code-note" class="note">-</div>',
    '  <div class="code">',
]
for i in range(LINES):
    lines.append(
        f'    <div id="code-r-{i}" class="row"><div id="code-n-{i}" class="no">{i + 1}</div>'
        f'<div id="code-h-{i}" class="hd">-</div><div id="code-t-{i}" class="ln">-</div></div>'
    )
lines += [
    '  </div>',
    '  <div class="foot">',
    '    <div class="btns">',
    '      <div id="code-up" class="btn"><div class="bt">Back</div></div>',
    '      <div id="code-down" class="btn"><div class="bt">More</div></div>',
    '      <div id="code-lines" class="note">-</div>',
    '    </div>',
    '    <div class="btns">',
    '      <div id="code-simplify" class="btn"><div id="code-simplify-label" class="bt">Simplify</div></div>',
    '      <div id="code-link" class="btn"><div class="bt">Copy link</div></div>',
    '    </div>',
    '  </div>',
    '</div>',
]

out = Path(__file__).resolve().parent.parent / 'public' / 'ui' / 'code.uikitml'
out.write_text('\n'.join(lines) + '\n', encoding='utf8')
print(f'wrote {out} ({LINES} lines, {len(TABS)} tabs)')
