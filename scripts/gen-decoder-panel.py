"""Generate public/ui/decoder.uikitml: the tap pad for the decoder game, one button per data qubit."""
from pathlib import Path

D = 5
rows = []
for r in range(D):
    cells = '\n'.join(f'      <div id="dec-b-{r}-{c}" class="q"><div id="dec-l-{r}-{c}" class="ql">.</div></div>' for c in range(D))
    rows.append(f'    <div id="dec-r-{r}" class="row">\n{cells}\n    </div>')
src = '''<!--
  The decoder game's tap pad: one button per data qubit, laid out like the
  lattice. Generated by scripts/gen-decoder-panel.py. UIKit units are cm.
-->
<style>
  .card {
    flex-direction: column;
    gap: 10;
    padding-top: 16;
    padding-bottom: 16;
    padding-left: 18;
    padding-right: 18;
    background-color: #1b1c1f;
    border-radius: 24;
    border-width: 1;
    border-color: #34363b;
    align-items: center;
  }
  .eyebrow { font-size: 11; font-weight: 600; color: #8a8d93; }
  .title { font-size: 16; font-weight: 700; color: #f2f3f5; }
  .grid { flex-direction: column; gap: 8; }
  .row { flex-direction: row; gap: 8; }
  .q {
    width: 44;
    height: 44;
    border-radius: 22;
    align-items: center;
    justify-content: center;
    background-color: #2f3135;
    cursor: pointer;
  }
  .ql { font-size: 13; font-weight: 700; color: #e4e6eb; }
  .note { font-size: 11; color: #8a8d93; }
</style>
<div class="card">
  <div id="dec-eyebrow" class="eyebrow">Be the decoder</div>
  <div class="title">Tap qubits to flip them</div>
  <div class="grid">
''' + '\n'.join(rows) + '''
  </div>
  <div id="dec-note" class="note">Clear every lit check.</div>
</div>
'''
Path('public/ui/decoder.uikitml').write_text(src, encoding='utf8')
print('ok')
